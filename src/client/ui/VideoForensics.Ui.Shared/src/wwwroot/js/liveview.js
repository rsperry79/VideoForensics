/**
 * Starts a live view connection from the browser to a server-bridged camera stream.
 * Creates a WebRTC peer connection, negotiates offer/answer with the server via SignalR,
 * and streams the camera video to the specified HTML video element.
 *
 * @param {HubConnection} hubConnection - The SignalR hub connection for WebRTC signaling.
 * @param {string} sessionId - The live view session ID on the server.
 * @param {string} videoElementId - The HTML video element ID to attach the stream to.
 * @returns {Promise<RTCPeerConnection>} The created peer connection, or rejects on error.
 */
export async function startLiveView(hubConnection, sessionId, videoElementId) {
    console.log(`[LiveView] Starting live view for session ${sessionId}`);

    const pc = new RTCPeerConnection({
        iceServers: [{ urls: "stun:stun.l.google.com:19302" }]
    });

    const videoElement = document.getElementById(videoElementId);
    if (!videoElement) {
        throw new Error(`Video element with ID '${videoElementId}' not found`);
    }

    // Handle incoming media tracks from server
    pc.ontrack = (event) => {
        console.log(`[LiveView] Received remote track: ${event.track.kind}`);
        if (event.streams && event.streams[0]) {
            videoElement.srcObject = event.streams[0];
        }
    };

    // Handle ICE candidates generated by the browser
    pc.onicecandidate = (event) => {
        if (event.candidate) {
            console.log(`[LiveView] Generated ICE candidate, sending to server`);
            hubConnection.invoke("SubmitIceCandidate", sessionId, event.candidate.candidate, event.candidate.sdpMLineIndex)
                .catch(err => console.error("[LiveView] Error submitting ICE candidate:", err));
        }
    };

    // Register handler for ICE candidates from server
    hubConnection.on("ReceiveIceCandidate", (candidate, sdpMLineIndex) => {
        console.log(`[LiveView] Received ICE candidate from server`);
        pc.addIceCandidate(new RTCIceCandidate({
            candidate: candidate,
            sdpMLineIndex: sdpMLineIndex
        })).catch(err => console.error("[LiveView] Error adding ICE candidate:", err));
    });

    try {
        // Store peer connection globally for addIceCandidate callback
        window._liveViewPeerConnection = pc;

        // Request offer from server
        console.log(`[LiveView] Requesting offer from server for session ${sessionId}`);
        const offerSdp = await hubConnection.invoke("RequestOffer", sessionId);
        console.log(`[LiveView] Received offer from server`);

        // Set remote description with server's offer
        await pc.setRemoteDescription({ type: "offer", sdp: offerSdp });

        // Create and send answer
        const answer = await pc.createAnswer();
        await pc.setLocalDescription(answer);
        console.log(`[LiveView] Sending answer to server`);
        await hubConnection.invoke("SubmitAnswer", sessionId, answer.sdp);

        console.log(`[LiveView] WebRTC negotiation complete, waiting for media`);
        return pc;
    } catch (error) {
        console.error(`[LiveView] Error negotiating WebRTC:`, error);
        pc.close();
        throw error;
    }
}

/**
 * Adds an ICE candidate received from the server to the peer connection.
 * Called by the Blazor page when the hub sends ReceiveIceCandidate.
 *
 * @param {string} candidate - The ICE candidate string.
 * @param {number} sdpMLineIndex - The SDP media line index.
 */
export async function addIceCandidate(candidate, sdpMLineIndex) {
    if (window._liveViewPeerConnection) {
        try {
            await window._liveViewPeerConnection.addIceCandidate(
                new RTCIceCandidate({
                    candidate: candidate,
                    sdpMLineIndex: sdpMLineIndex
                }));
            console.log(`[LiveView] Added ICE candidate from server`);
        } catch (err) {
            console.error(`[LiveView] Error adding ICE candidate:`, err);
        }
    }
}

/**
 * Stops an active live view connection.
 *
 * @param {RTCPeerConnection} pc - The peer connection to close.
 */
export function stopLiveView(pc) {
    if (pc && pc.signalingState !== "closed") {
        console.log(`[LiveView] Closing peer connection`);
        pc.close();
    }
}
