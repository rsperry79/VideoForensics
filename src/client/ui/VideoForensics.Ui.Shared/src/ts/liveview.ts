const SIGNALR_SCRIPT = "_content/VideoForensics.Client.Ui.Shared/lib/signalr/signalr.min.js";

// One peer connection per live view session, keyed by session id. Recorded once negotiation succeeds.
const peerConnections = new Map<string, RTCPeerConnection>();

/**
 * Loads the vendored SignalR browser client on first use. The Blazor script bundles its own private
 * copy that it does not expose, so the live view page brings the standard client.
 */
function loadSignalR(): Promise<SignalRLibrary> {
    if (window.signalR) {
        return Promise.resolve(window.signalR);
    }

    return new Promise((resolve, reject) => {
        const script = document.createElement("script");
        script.src = SIGNALR_SCRIPT;
        script.onload = () => (window.signalR ? resolve(window.signalR) : reject(new Error("SignalR client did not register")));
        script.onerror = () => reject(new Error(`Could not load the SignalR client from '${SIGNALR_SCRIPT}'`));
        document.head.appendChild(script);
    });
}

/**
 * Opens the SignalR connection the live view signals over. The hub authenticates the paired session token,
 * which travels as the access_token query parameter on the WebSocket upgrade.
 * Returns a .NET-visible reference, which the page passes back to startLiveView and stopHubConnection.
 *
 * @param hubUrl - Absolute URL of the live view signaling hub.
 * @param accessToken - The signed-in operator's session token.
 */
export async function initializeHubConnection(
    hubUrl: string,
    accessToken: string | null,
    callbacks?: LiveViewConnectionCallbacks,
): Promise<unknown> {
    const signalR = await loadSignalR();
    const connection = new signalR.HubConnectionBuilder()
        .withUrl(hubUrl, { accessTokenFactory: () => accessToken ?? "" })
        .withAutomaticReconnect()
        .build();
    if (callbacks) {
        // Each state change calls the matching [JSInvokable] method on the page. A failed call is logged, not thrown.
        connection.onreconnecting(() => notifyConnectionState(callbacks, "OnHubReconnecting"));
        connection.onreconnected(() => notifyConnectionState(callbacks, "OnHubReconnected"));
        connection.onclose(() => notifyConnectionState(callbacks, "OnHubConnectionClosed"));
    }
    await connection.start();
    // Return the connection itself: startLiveView calls .invoke on it. A DotNet reference is a wrapper without them.
    return connection;
}

/**
 * Closes the signaling connection when the page goes away.
 *
 * @param hubConnection - The connection returned by initializeHubConnection.
 */
export async function stopHubConnection(hubConnection: SignalRHubConnection | null | undefined): Promise<void> {
    if (hubConnection) {
        await hubConnection.stop();
    }
}

/**
 * Starts a live view connection from the browser to a server-bridged camera stream.
 * Creates a WebRTC peer connection, negotiates offer/answer with the server via SignalR,
 * and streams the camera video to the specified HTML video element.
 *
 * @param hubConnection - The SignalR hub connection for WebRTC signaling.
 * @param sessionId - The live view session ID on the server.
 * @param videoElementId - The HTML video element ID to attach the stream to.
 * @returns The created peer connection, or rejects on error.
 */
export async function startLiveView(
    hubConnection: SignalRHubConnection,
    sessionId: string,
    videoElementId: string,
): Promise<RTCPeerConnection> {
    console.log(`[LiveView] Starting live view for session ${sessionId}`);

    const pc = new RTCPeerConnection({
        iceServers: [{ urls: "stun:stun.l.google.com:19302" }]
    });

    const videoElement = document.getElementById(videoElementId) as HTMLVideoElement | null;
    if (!videoElement) {
        pc.close();
        throw new Error(`Video element with ID '${videoElementId}' not found`);
    }

    // Handle incoming media tracks from server
    pc.ontrack = (event: RTCTrackEvent) => {
        console.log(`[LiveView] Received remote track: ${event.track.kind}`);
        if (event.streams && event.streams[0]) {
            videoElement.srcObject = event.streams[0];
        }
    };

    // Handle ICE candidates generated by the browser
    pc.onicecandidate = (event: RTCPeerConnectionIceEvent) => {
        if (event.candidate) {
            console.log(`[LiveView] Generated ICE candidate, sending to server`);
            hubConnection.invoke("SubmitIceCandidate", sessionId, event.candidate.candidate, event.candidate.sdpMLineIndex)
                .catch((err: unknown) => console.error("[LiveView] Error submitting ICE candidate:", err));
        }
    };

    try {
        // Request offer from server
        console.log(`[LiveView] Requesting offer from server for session ${sessionId}`);
        const offerSdp = await hubConnection.invoke<string>("RequestOffer", sessionId);
        console.log(`[LiveView] Received offer from server`);

        // Set remote description with server's offer
        await pc.setRemoteDescription({ type: "offer", sdp: offerSdp });

        // Create and send answer
        const answer = await pc.createAnswer();
        await pc.setLocalDescription(answer);
        console.log(`[LiveView] Sending answer to server`);
        await hubConnection.invoke("SubmitAnswer", sessionId, answer.sdp);

        console.log(`[LiveView] WebRTC negotiation complete, waiting for media`);
        peerConnections.set(sessionId, pc);
        return pc;
    } catch (error) {
        console.error(`[LiveView] Error negotiating WebRTC:`, error);
        pc.close();
        throw error;
    }
}

/**
 * Stops an active live view connection.
 *
 * @param sessionId - The live view session whose peer connection to close. An unknown id does nothing.
 */
export function stopLiveView(sessionId: string): void {
    const pc = peerConnections.get(sessionId);
    if (pc) {
        peerConnections.delete(sessionId);
        console.log(`[LiveView] Closing peer connection`);
        pc.close();
    }
}

/**
 * Pauses one live player and saves its current frame as a PNG download. Does nothing when the player has no frame yet.
 * @param videoElementId - The live player's video element id.
 * @param fileName - The file name for the download.
 */
export function grabLiveFrame(videoElementId: string, fileName: string): void {
    const video = document.getElementById(videoElementId) as HTMLVideoElement | null;
    if (!video || video.videoWidth === 0) {
        return;
    }

    // Pause first, so the frame on screen is the frame saved.
    video.pause();
    const canvas = document.createElement("canvas");
    canvas.width = video.videoWidth;
    canvas.height = video.videoHeight;
    const context = canvas.getContext("2d");
    if (!context) {
        return;
    }

    context.drawImage(video, 0, 0, canvas.width, canvas.height);
    const link = document.createElement("a");
    link.href = canvas.toDataURL("image/png");
    link.download = fileName;
    link.click();
}

/**
 * Expands one live player to full screen, or leaves full screen when it is already showing one.
 * @param videoElementId - The live player's video element id.
 */
export function toggleFullscreen(videoElementId: string): void {
    const video = document.getElementById(videoElementId);
    if (!video) {
        return;
    }

    if (document.fullscreenElement) {
        void document.exitFullscreen();
    } else {
        void video.requestFullscreen();
    }
}

/** The page's [JSInvokable] methods that hear the hub connection's state changes. */
export interface LiveViewConnectionCallbacks {
    invokeMethodAsync(methodName: string): Promise<unknown>;
}

function notifyConnectionState(callbacks: LiveViewConnectionCallbacks, methodName: string): void {
    callbacks.invokeMethodAsync(methodName).catch((err: unknown) => console.error(`[LiveView] Could not notify the page (${methodName}):`, err));
}

// The subset of the SignalR HubConnection surface this module uses. Typed here so the module
// does not depend on the SignalR package's type declarations, which the browser build never loads.
interface SignalRHubConnection {
    invoke<T = void>(methodName: string, ...args: unknown[]): Promise<T>;
    start(): Promise<void>;
    stop(): Promise<void>;
    onreconnecting(callback: () => void): void;
    onreconnected(callback: () => void): void;
    onclose(callback: () => void): void;
}

interface SignalRHubConnectionBuilder {
    withUrl(url: string, options?: { accessTokenFactory?: () => string | Promise<string> }): SignalRHubConnectionBuilder;
    withAutomaticReconnect(): SignalRHubConnectionBuilder;
    build(): SignalRHubConnection;
}

interface SignalRLibrary {
    HubConnectionBuilder: new () => SignalRHubConnectionBuilder;
}
