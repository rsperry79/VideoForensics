namespace VideoForensics.Client.WebApp.Startup
{
    /// <summary>Login-pipeline security services (GeoIP, threat intel, banned IPs, failed-login tracking), moved out of Program.cs.</summary>
    internal static class WebAppLoginSecurityRegistration
    {
        /// <summary>Adds the login-pipeline security services. <paramref name="geoLite2DbPath"/> is the MaxMind database path.</summary>
        internal static IServiceCollection AddWebAppLoginSecurity(this IServiceCollection services, string geoLite2DbPath)
        {
        services.AddScoped<IGeoIpLookupService>(_ => new MaxMindGeoIpLookupService(geoLite2DbPath));

        // Threat intelligence blocklist service (null implementation for now; actual feed fetching is separate work)
        services.AddScoped<IThreatIntelBlocklistService, NullThreatIntelBlocklistService>();

        // Banned IP range matching service
        services.AddScoped<IBannedIpMatchService, BannedIpMatchService>();
        // Singleton: the per-IP lockout counters must outlive a single request. Resolves its scoped repository per ban write.
        services.AddSingleton<IFailedLoginIpTracker, FailedLoginIpTracker>();
            return services;
        }
    }
}
