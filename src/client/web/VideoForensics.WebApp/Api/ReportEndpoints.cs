                return Results.Ok(report.ToDto());
            }
            catch (Exception ex)
            {
                return Results.BadRequest(new { error = $"Failed to generate forensic analysis report: {ex.Message}" });
            }
        }

        private static async Task<IResult> BuildSignalAnomalyReportAsync(
            Guid? deviceId,
            DateTime? fromUtc,
            DateTime? toUtc,
            IReportGenerationService reportService,
            CancellationToken ct)
        {
            try
            {
                DateTime from = fromUtc ?? DateTime.UtcNow.AddDays(-7);
                DateTime to = toUtc ?? DateTime.UtcNow;

                SignalAnomalyReport report = await reportService.BuildSignalAnomalyReportAsync(deviceId, from, to, ct);
                return Results.Ok(report.ToDto());
            }
            catch (Exception ex)
            {
                return Results.BadRequest(new { error = $"Failed to generate signal anomaly report: {ex.Message}" });
            }
        }

        private static async Task<IResult> BuildAccessControlReportAsync(
            Guid? deviceId,
            DateTime? fromUtc,
            DateTime? toUtc,
            IReportGenerationService reportService,
            CancellationToken ct)
        {
            try
            {
                DateTime from = fromUtc ?? DateTime.UtcNow.AddDays(-7);
                DateTime to = toUtc ?? DateTime.UtcNow;

                AccessControlReport report = await reportService.BuildAccessControlReportAsync(deviceId, from, to, ct);
                return Results.Ok(report.ToDto());
            }
            catch (Exception ex)
            {
                return Results.BadRequest(new { error = $"Failed to generate access control report: {ex.Message}" });
            }
        }

        private static async Task<IResult> BuildChainOfCustodyReportAsync(
            Guid? deviceId,
            DateTime? fromUtc,
            DateTime? toUtc,
            IReportGenerationService reportService,
            CancellationToken ct)
        {
            try
            {
                DateTime from = fromUtc ?? DateTime.UtcNow.AddDays(-7);
