            }
        }

        private static async Task<IResult> WriteReportAsync(
            WriteReportRequest request,
            IReportGenerationService reportService,
            CancellationToken ct)
        {
            try
            {
                await reportService.WriteReportAsync(request.ReportDto, request.Format, ct);
                return Results.Ok(new { message = "Report successfully exported to file." });
            }
            catch (Exception ex)
            {
                return Results.BadRequest(new { error = $"Failed to write report: {ex.Message}" });
            }
        }
    }

    /// <summary>Request for writing a report to file.</summary>
    /// <param name="ReportDto">The report DTO to write (one of: EvidenceReviewReportDto, ForensicAnalysisReportDto, SignalAnomalyReportDto, AccessControlReportDto, ChainOfCustodyReportDto).</param>
    /// <param name="Format">Export format: "json", "xml", or "csv".</param>
    public record WriteReportRequest(
        object ReportDto,
        string Format
    );
}
